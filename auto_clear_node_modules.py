#!/usr/bin/env python3
"""
Fast recursive cleaner for node_modules + optional other folders/files.
Skips entering folders that are targeted for deletion.
"""

import os
import shutil
import sys
from pathlib import Path
from typing import List, Set


def get_directory_from_user() -> Path:
    print("\nPaste the folder path to clean (drag & drop works):")
    while True:
        inp = input("→ ").strip().strip("'\"")
        if not inp:
            print("Please enter a path.")
            continue
        p = Path(inp).expanduser().resolve()
        if not p.exists():
            print("❌ Path does not exist")
            continue
        if not p.is_dir():
            print("❌ Not a directory")
            continue
        return p


def ask_extra_patterns() -> Set[str]:
    print("\nDo you want to ALSO delete other folders/files?")
    print("Examples: .next, dist, build, .cache, coverage, node_modules~")
    print("(leave empty = only clean node_modules)\n")

    inp = input("Additional names (comma or semicolon separated): ").strip()
    if not inp:
        return set()

    # Normalize separators and clean
    raw = inp.replace(";", ",").split(",")
    cleaned = {x.strip() for x in raw if x.strip()}

    if not cleaned:
        return set()

    print("\nWill also try to delete:")
    for pat in sorted(cleaned):
        print(f"  • {pat}")
    print()

    return cleaned


def find_target_folders(start_path: Path, targets: Set[str]) -> List[Path]:
    """
    Find all folders/files matching any name in targets.
    Never enters into any folder that matches a target name.
    """
    print(f"\nScanning for: {', '.join(sorted(targets))} ...\n")

    found = []
    targets_lower = {
        t.lower() for t in targets
    }  # case-insensitive match on Windows/macOS

    for root, dirs, files in os.walk(start_path, topdown=True):
        root_path = Path(root)

        # Check directories
        to_remove_from_walk = []
        for d in dirs:
            d_path = root_path / d
            d_lower = d.lower()
            if d_lower in targets_lower or d in targets:
                found.append(d_path)
                to_remove_from_walk.append(d)

        # Remove targets from walk list → we won't enter them
        for d in to_remove_from_walk:
            dirs.remove(d)

        # Check files (if someone wants to delete e.g. yarn.lock or package-lock.json)
        for f in files:
            f_lower = f.lower()
            if f_lower in targets_lower or f in targets:
                found.append(root_path / f)

    return sorted(found)


def human_size(b: int) -> str:
    for unit in ["B", "KiB", "MiB", "GiB", "TiB"]:
        if b < 1024:
            return f"{b:.1f} {unit}"
        b /= 1024
    return f"{b:.1f} PiB"


def estimate_size(path: Path) -> int:
    total = 0
    try:
        if path.is_file():
            return path.stat().st_size
        for dirpath, dirnames, filenames in os.walk(path, followlinks=False):
            for fn in filenames:
                try:
                    total += (Path(dirpath) / fn).stat().st_size
                except:
                    pass
    except:
        pass
    return total


def main():
    print("=== Multi-target Folder Cleaner ===\n")

    root = get_directory_from_user()
    print(f"→ Working in: {root}\n")

    # Always include node_modules
    targets = {"node_modules"}
    extra = ask_extra_patterns()
    targets.update(extra)

    items = find_target_folders(root, targets)

    if not items:
        print("Nothing matched the patterns ✓")
        return

    print(f"\nFound {len(items)} item(s) to delete:\n")

    total_size = 0
    for i, path in enumerate(items, 1):
        size = estimate_size(path)
        total_size += size
        rel = path.relative_to(root)
        kind = "file" if path.is_file() else "folder"
        print(f"  {i:2d}. {rel}  ({kind})")
        print(f"      ≈ {human_size(size)}")
        print()

    print(f"Estimated total space to free ≈ {human_size(total_size)}")
    print("-" * 70)

    print("\n!!! THIS WILL PERMANENTLY DELETE THE LISTED ITEMS AND ALL CONTENTS !!!")
    confirm = input("\nType YES to delete everything listed above: ").strip()

    if confirm.upper() != "YES":
        print("Aborted.")
        return

    print("\nDeleting...\n")
    success = 0

    for path in items:
        try:
            if path.is_file() or path.is_symlink():
                path.unlink()
            else:
                shutil.rmtree(path, ignore_errors=False)
            print(f"✔ Removed: {path.relative_to(root)}")
            success += 1
        except Exception as e:
            print(f"✘ Failed: {path.relative_to(root)} → {e.__class__.__name__}: {e}")

    print(f"\nFinished. Successfully deleted {success}/{len(items)} items.")
    print(f"≈ Freed {human_size(total_size)} (estimate)")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nInterrupted.")
    except Exception as e:
        print(f"Error: {e}", file=sys.stderr)
        sys.exit(1)
