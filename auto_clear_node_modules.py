#!/usr/bin/env python3
"""
Recursively find and delete top-level 'node_modules' folders.
Skips searching inside any node_modules directory.
"""

import os
import shutil
import sys
from pathlib import Path


def get_directory_from_user() -> Path:
    """Let user input or drag-drop a folder path"""
    print("\nPaste the folder path where you want to search for node_modules")
    print("(you can drag the folder into the terminal window)\n")

    while True:
        path_input = input("→ ").strip().strip("'\"")

        if not path_input:
            print("Please enter a path.")
            continue

        path = Path(path_input).expanduser().resolve()

        if not path.exists():
            print("❌ Path does not exist")
            continue

        if not path.is_dir():
            print("❌ This is not a directory")
            continue

        return path


def find_top_level_node_modules(start_path: Path) -> list[Path]:
    """
    Find 'node_modules' folders, but do NOT enter already found node_modules dirs.
    This avoids scanning nested dependencies → much faster.
    """
    print("\nScanning for top-level node_modules folders...\n")

    found = []
    node_modules_name = "node_modules"

    # Use os.walk instead of rglob → we can prune directories
    for root, dirs, _ in os.walk(start_path, topdown=True):
        # Important: modify dirs in-place to prune
        if node_modules_name in dirs:
            nm_path = Path(root) / node_modules_name
            if nm_path.is_dir():
                found.append(nm_path)
            # Remove from dirs list → os.walk will NOT enter this folder
            dirs.remove(node_modules_name)

        # Also skip any other node_modules we already found higher up
        dirs[:] = [d for d in dirs if d != node_modules_name]

    return sorted(found)


def human_size(size_bytes: int) -> str:
    """Convert bytes to human readable format"""
    for unit in ["B", "KiB", "MiB", "GiB", "TiB"]:
        if size_bytes < 1024.0:
            return f"{size_bytes:.1f} {unit}"
        size_bytes /= 1024.0
    return f"{size_bytes:.1f} PiB"


def estimate_folder_size(path: Path) -> int:
    """Quick size estimation — may be approximate if permission issues"""
    total = 0
    try:
        for dirpath, dirnames, filenames in os.walk(path, followlinks=False):
            for f in filenames:
                try:
                    total += (Path(dirpath) / f).stat().st_size
                except (PermissionError, FileNotFoundError, OSError):
                    pass
    except Exception:
        pass
    return total


def main():
    print("=== Fast node_modules Cleaner (skips nested node_modules) ===\n")

    root_dir = get_directory_from_user()
    print(f"\nTarget folder: {root_dir}\n")

    node_modules_folders = find_top_level_node_modules(root_dir)

    if not node_modules_folders:
        print("No node_modules folders found ✓\n")
        sys.exit(0)

    print(f"Found {len(node_modules_folders)} top-level node_modules folder(s):\n")

    total_size = 0
    for i, folder in enumerate(node_modules_folders, 1):
        size = estimate_folder_size(folder)
        total_size += size
        rel_path = folder.relative_to(root_dir)
        print(f"  {i:2d}. {rel_path}")
        print(f"      ≈ {human_size(size)}")
        print()

    print(f"→ Estimated total space to free: {human_size(total_size)}")
    print("-" * 60)

    print("\n!!! This will DELETE all listed folders and everything inside them !!!")
    print("    (action cannot be undone)\n")

    confirm = input("Type YES to proceed with deletion: ").strip()
    if confirm.upper() != "YES":
        print("Aborted — nothing was deleted.")
        sys.exit(0)

    print("\nDeleting...\n")
    success = 0

    for folder in node_modules_folders:
        try:
            shutil.rmtree(folder, ignore_errors=False)
            print(f"✔ Deleted: {folder.relative_to(root_dir)}")
            success += 1
        except Exception as e:
            print(f"✘ Failed: {folder.relative_to(root_dir)}")
            print(f"   → {e.__class__.__name__}: {e}")

    print(
        f"\nDone. Successfully removed {success}/{len(node_modules_folders)} folders."
    )
    print(f"≈ Freed {human_size(total_size)} (estimate)")


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        print("\nInterrupted. Exiting cleanly.")
    except Exception as e:
        print(f"\nUnexpected error: {e}", file=sys.stderr)
        sys.exit(1)
